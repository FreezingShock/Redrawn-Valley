#!/usr/bin/env python3
"""Self-hosted fonts: fingerprint the subset files, write the @font-face sheet, and keep every page head in step.

Run: python3 scripts/build_fonts.py          (rewrites assets/fonts/ and the page heads)
     python3 scripts/build_fonts.py --check  (exit 1 if anything is stale; writes nothing)
     python3 scripts/build_fonts.py --subset RAW_DIR   (rebuild scripts/data/fonts/ from the Google woff2 files, see below)

Sources live in scripts/data/fonts/ (Latin subsets, hinting off). Output names carry a content hash, so Vercel serves
them with a one-year immutable cache (vercel.json) and a changed font is a new URL. Pages preload only the display (Shantell Sans)
and body (Figtree) files. DM Mono and Caveat are not preloaded: the browser fetches a face only when text on the page uses it,
so Caveat (page notes) and DM Mono (numerals, code) cost nothing on pages that do not show them.

--subset expects RAW_DIR with the full Google Fonts woff2 files (latin) named shantell-sans-400-700.woff2, figtree-400-700.woff2,
caveat-500-700.woff2 and dm-mono-400.woff2. It keeps Basic Latin, Latin-1, common punctuation and a few symbols; limits Shantell
to the axes the site uses (wght 400-700, INFM 70-100, BNCE -100..100); and pins Caveat to weight 700. Needs fontTools and brotli.
All four families are SIL OFL 1.1 with no Reserved Font Name, so subsetting and self-hosting are allowed (see assets/fonts/OFL.txt)."""
import sys, re, hashlib, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import assetver

root = pathlib.Path(__file__).resolve().parent.parent
SRC = root / 'scripts' / 'data' / 'fonts'
OUT = root / 'assets' / 'fonts'
# family, source file, css descriptors, preload on every page
FACES = [
    ('Shantell Sans', 'shantell-sans', 'font-weight:400 700', True),
    ('Figtree', 'figtree', 'font-weight:400 700', True),
    ('DM Mono', 'dm-mono', 'font-weight:400', False),
    ('Caveat', 'caveat', 'font-weight:700', False),
]
UNICODES = ('U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,U+2022,U+2026,'
            'U+2032,U+2033,U+2212,U+00D7,U+2190-2193,U+20AC,U+2122')
SKIP = {'fonts/index.html'}  # the type lab loads its own candidate families from Google on purpose


def h8(b): return hashlib.sha1(b).hexdigest()[:8]


def plan():
    """Return {path: bytes} for everything under assets/fonts that this script owns, plus the head lines (relative to the site root)."""
    files, preload, css = {}, [], []
    for fam, stem, desc, pre in FACES:
        data = (SRC / f'{stem}.woff2').read_bytes()
        name = f'{stem}.{h8(data)}.woff2'
        files[name] = data
        css.append(f'@font-face{{font-family:"{fam}";font-style:normal;{desc};font-display:swap;src:url({name}) format("woff2")}}')
        if pre: preload.append(name)
    sheet = ('/* generated by scripts/build_fonts.py: do not edit */\n' + '\n'.join(css) + '\n').encode()
    sheet_name = f'fonts.{h8(sheet)}.css'
    files[sheet_name] = sheet
    return files, preload, sheet_name


def head_block(up, preload, sheet_name):
    lines = [f'<link rel="preload" href="{up}assets/fonts/{n}" as="font" type="font/woff2" crossorigin>' for n in preload]
    lines.append(f'<link rel="stylesheet" href="{up}assets/fonts/{sheet_name}">')
    return '\n'.join(lines)


def block_for(up):
    _, preload, sheet = plan()
    return head_block(up, preload, sheet)


LINE = re.compile(r'^[ \t]*<link[^>]*(?:fonts\.googleapis\.com|fonts\.gstatic\.com|assets/fonts/)[^>]*>[ \t]*\n', re.M)


def rewrite(text, block):
    """Replace the Google (or previous self-hosted) font links with the current block, at the position of the first one."""
    m = LINE.search(text)
    if not m:  # a page that has the design tokens but no font links yet (a new page): add the block before them
        t = re.search(r'^[ \t]*<link[^>]*assets/rds/tokens\.css[^>]*>', text, re.M)
        return text[:t.start()] + block + '\n' + text[t.start():] if t else text
    first = m.start()
    rest = LINE.sub('', text)
    return rest[:first] + block + '\n' + rest[first:]


def pages():
    for f in sorted(root.rglob('*.html')):
        rel = f.relative_to(root).as_posix()
        if rel in SKIP or rel.startswith(('node_modules/', '.git/')): continue
        yield f, rel


def up_for(f):
    return '../' * (len(f.relative_to(root).parts) - 1)


def subset(raw):
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
    from fontTools import subset as sub
    raw = pathlib.Path(raw)
    jobs = [('shantell-sans-400-700', 'shantell-sans', {'INFM': (70, 100), 'BNCE': (-100, 100)}, ['kern', 'liga', 'calt', 'ccmp', 'locl', 'mark', 'mkmk']),
            ('figtree-400-700', 'figtree', None, ['kern', 'liga', 'calt', 'ccmp', 'locl', 'mark', 'mkmk', 'tnum', 'lnum', 'case']),
            ('caveat-500-700', 'caveat', {'wght': 700}, ['kern', 'liga', 'calt', 'ccmp', 'locl']),
            ('dm-mono-400', 'dm-mono', None, ['kern', 'tnum', 'zero', 'ccmp', 'locl'])]
    SRC.mkdir(parents=True, exist_ok=True)
    for src, dst, limits, feats in jobs:
        f = TTFont(raw / f'{src}.woff2')
        if limits: f = instancer.instantiateVariableFont(f, limits, inplace=False)
        o = sub.Options(); o.layout_features = feats; o.notdef_outline = True; o.name_IDs = [0, 1, 2, 3, 4, 6, 13, 14]; o.hinting = False
        s = sub.Subsetter(o); s.populate(unicodes=sub.parse_unicodes(UNICODES)); s.subset(f)
        f.flavor = 'woff2'; f.save(SRC / f'{dst}.woff2')
        print(dst, (SRC / f'{dst}.woff2').stat().st_size, 'bytes')


def main():
    if '--subset' in sys.argv:
        subset(sys.argv[sys.argv.index('--subset') + 1]); return 0
    check = '--check' in sys.argv
    files, preload, sheet = plan()
    stale = []
    OUT.mkdir(parents=True, exist_ok=True)
    have = {p.name for p in OUT.iterdir() if p.suffix in ('.woff2', '.css')}
    for name, data in files.items():
        p = OUT / name
        if not p.exists() or p.read_bytes() != data:
            stale.append(f'assets/fonts/{name}')
            if not check: p.write_bytes(data)
    for name in sorted(have - set(files)):
        stale.append(f'assets/fonts/{name} (old)')
        if not check: (OUT / name).unlink()
    for f, rel in pages():
        t = f.read_text(encoding='utf-8')
        new = rewrite(t, head_block(up_for(f), preload, sheet))
        if assetver.strip(new) != assetver.strip(t):   # stamps are assetver's job, so a stamped copy is not stale
            stale.append(rel)
            if not check: f.write_text(new, encoding='utf-8')
    if check:
        if stale: print('fonts stale: ' + ', '.join(stale[:8]) + (' ...' if len(stale) > 8 else '') + ' (run python3 scripts/build_fonts.py)'); return 1
        return 0
    print(f'{len(stale)} files updated; display+body preload: {", ".join(preload)}; sheet {sheet}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
