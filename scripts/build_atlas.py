VOID = {'br', 'img', 'hr', 'meta', 'link', 'input', 'source', 'path', 'circle', 'rect', 'line', 'use', 'ellipse', 'stop', 'col', 'wbr'}
SKIP = {'script', 'style', 'svg', 'noscript', 'template', 'head'}
SECTION_LABEL = {'guide': 'Field guide', 'studies': 'Study', 'notes': 'Note', 'lab': 'Lab note'}
KIND_ORDER = {'term': 0, 'place': 1, 'page': 2, 'drawing': 3, 'source': 4}
MAX_PAGES, MAX_ANCHORS = 4, 3

class N:
    __slots__ = ('tag', 'a', 'kids', 'parent')
    def __init__(s, tag, a, parent): s.tag, s.a, s.kids, s.parent = tag, a, [], parent
    def cls(s): return (s.a.get('class') or '').split()
    def text(s, skip_cls=()):
        out = []
        def go(n):
            for k in n.kids:
                if isinstance(k, str): out.append(k)
                elif k.tag in SKIP or any(c in skip_cls for c in k.cls()): continue
                else: go(k)
        go(s); return clean(''.join(out))
    def walk(s):
        yield s
        for k in s.kids:
            if not isinstance(k, str): yield from k.walk()
    def up(s):
        n = s
        while n: yield n; n = n.parent

class Tree(HTMLParser):
    def __init__(s):
        super().__init__(convert_charrefs=True); s.root = N('#root', {}, None); s.cur = s.root
    def handle_starttag(s, tag, attrs):
        if tag in ('li', 'dd', 'dt', 'p'):                 # implied end tags in hand-written markup
            n = s.cur
            while n and n.tag not in ('ul', 'ol', 'dl', 'div', 'section', 'article', 'main', 'body', '#root'):
                if n.tag == tag: s.cur = n.parent; break
                n = n.parent
        n = N(tag, dict(attrs), s.cur); s.cur.kids.append(n)
        if tag not in VOID: s.cur = n
    def handle_startendtag(s, tag, attrs): s.cur.kids.append(N(tag, dict(attrs), s.cur))
    def handle_endtag(s, tag):
        n = s.cur
        while n and n.tag != tag and n is not s.root: n = n.parent
        if n is not s.root and n.tag == tag: s.cur = n.parent
    def handle_data(s, d): s.cur.kids.append(d)

def clean(t): return re.sub(r'\s+', ' ', t.replace(' ', ' ')).strip()
def esc(t): return html.escape(t, quote=True)
def slug(t): return re.sub(r'[^a-z0-9]+', '-', t.lower()).strip('-') or 'x'

def page_url(f):
    rel = f.relative_to(root)
    return '' if rel.as_posix() == 'index.html' else (rel.parent.as_posix() + '/' if rel.name == 'index.html' else rel.as_posix())

def load_pages():
    pages = []
    for f in html_files():
        rel = f.relative_to(root)
        if rel.name == '404.html' or rel.parts[0] == 'a-z': continue
        t = Tree(); t.feed(f.read_text(encoding='utf-8'))
        meta = {(n.a.get('name') or '').lower(): n.a.get('content', '') for n in t.root.walk() if n.tag == 'meta'}
        title_n = next((n for n in t.root.walk() if n.tag == 'title'), None)
        title = clean(title_n.text()) if title_n else ''
        if 'noindex' in meta.get('robots', '') or not title: continue
        url = page_url(f)
        if url == '': continue                                  # the home page is not an entry
        h1 = next((n for n in t.root.walk() if n.tag == 'h1'), None)
        head = clean(title.split(' | ')[0]) or (h1.text() if h1 else url)
        parts = url.split('/')
        pages.append({'url': url, 'sec': parts[0] if len(parts) > 1 else '', 'title': head, 'desc': clean(meta.get('description', '')),
                      'tree': t.root, 'hub': url.rstrip('/').count('/') == 0 and url.endswith('/'), 'file': f,
                      'tagline': next((n.text() for n in t.root.walk() if 'rds-article__tagline' in n.cls()), '')})
    return pages

def in_skipped(n):
    """True for shell chrome and the parts of a page that are lists rather than prose."""
    for a in n.up():
        if a.tag in SKIP or (a.tag in ('header', 'footer') and ('data-rv-shell' in a.a or 'data-rds-nav' in a.a)): return True
        if 'data-rv-noindex' in a.a or any(c in ('rds-contents', 'rds-toc', 'rds-crumbs', 'rds-notes', 'rv-sources', 'rv-tabbar') for c in a.cls()): return True
        if a.a.get('id') == 'sources': return True
    return False

def anchored(page):
    """Yield (node, anchor_id, anchor_label) in document order; the anchor is the nearest section or heading with an id."""
    cur = {'id': None, 'label': None}
    def go(n, sec):
        for k in n.kids:
            if isinstance(k, str): continue
            s = sec
            if k.tag in ('section', 'article') and k.a.get('id'): s = k.a['id']; cur['id'], cur['label'] = s, None
            if k.tag in ('h2', 'h3'):
                hid = k.a.get('id')
                cur['id'] = s if (s and (not hid or hid.endswith('-h'))) else (hid or s)
                cur['label'] = re.sub(r'^\d{1,2}(?=[A-Z])', '', clean(re.sub(r'#$', '', k.text(('rds-anchor',)))))
            yield k, cur['id'], cur['label']
            if k.tag not in SKIP: yield from go(k, s)
    yield from go(page['tree'], None)

def short(t, n=72):
    t = clean(t)
    if len(t) <= n: return t
    c = t[:n].rsplit(' ', 1)[0].rstrip(',;:-')
    return c + '…'

def norm_url(u):
    u = re.sub(r'^https?://(www\.)?', '', u.strip().lower()); return re.sub(r'[#?].*$', '', u).rstrip('/')

def extract_sources(page):
    """Source list items on a page, each with the in-text links that point at it."""
    lis = {}
    for n in page['tree'].walk():
        if n.tag != 'li' or not n.a.get('id'): continue
        in_list = any((a.tag in ('ol', 'ul') and ('rds-notes' in a.cls() or 'rv-sources' in a.cls())) or
                      ('rv-sources' in a.cls()) or a.a.get('id') == 'sources' for a in n.up())
        if in_list and not any(a.tag == 'aside' for a in n.up()): lis[n.a['id']] = n
    uses = {k: [] for k in lis}
    for n, aid, label in anchored(page):
        if n.tag != 'a' or not n.a.get('href', '').startswith('#') or in_skipped(n): continue
        key = n.a['href'][1:]
        if key not in uses or any('rds-back' in c or 'rv-back' in c for c in n.cls()): continue
        uid = next((a.a['id'] for a in n.up() if a.tag in ('sup', 'span', 'a') and a.a.get('id')), None) or n.a.get('id')
        uses[key].append((uid, aid, label))
    out = []
    for k, li in lis.items():
        link = next((a for a in li.walk() if a.tag == 'a' and re.match(r'https?:', a.a.get('href', ''))), None)
        cite = next((a for a in li.walk() if a.tag == 'cite'), None)
        txt = cite.text() if cite else clean(li.text(('rds-back', 'rv-back', 'rds-kind')))
        txt = re.sub(r'^\[\d+\]\s*', '', txt)
        if link and not cite:
            lt = link.text(); txt = clean(txt.replace(lt, '')) if lt else txt
        txt = re.sub(r'\s*(https?://\S+|www\.\S+)\s*$', '', txt).strip(' .') + '.' if txt else ''
        txt = re.sub(r'[;:,]\s*[^;:,.]{0,40}\bat\.$', '.', txt.replace('..', '.')); txt = re.sub(r'(?:\s*(?:Abstract|Excerpt|Summary))?[:;,]\.$', '.', re.sub(r'\s+([;,])', r'\1', txt)).replace('”.\u2019', '”').replace('.”.', '.”')
        kind = next((a.text() for a in li.walk() if 'rds-kind' in a.cls()), '')
        url = link.a['href'] if link else ''
        out.append({'id': k, 'text': txt, 'url': url, 'kind': kind, 'uses': uses[k], 'key': norm_url(url) if url else slug(txt)[:90]})
    return out

def extract_figures(page):
    figs = []
    for n, aid, label in anchored(page):
        if in_skipped(n): continue
        if n.tag == 'figure' and False: pass
        cap = None
        if n.tag == 'figure':
            c = next((k for k in n.walk() if k.tag == 'figcaption'), None)
            cap = c.text() if c else None
            fid = n.a.get('id') or aid
        elif 'rds-infobox__cap' in n.cls():
            cap = n.text(); fid = aid; cap = 'Sketch: ' + cap if cap else None
        if not cap: continue
        m = re.match(r'^(Fig(?:ure)?\.?\s*\d+)\s*[:.—-]?\s*', cap, re.I)
        num = m.group(1) if m else ''
        body = cap[m.end():] if m else cap
        body = re.sub(r'^Sketch:\s*', '', body)
        first = re.split(r'(?<=[a-z0-9)])[.;:]\s', body, maxsplit=1)[0].rstrip('.')
        head = short(first[:1].upper() + first[1:], 64)
        if len(head) < 8: continue
        figs.append({'head': head, 'cap': short(body, 220), 'num': num, 'anchor': fid, 'label': label})
    return figs if len(figs) <= 12 else []                    # a gallery of tiny specimens is not a list of drawings

def pattern(names):
    alts = '|'.join(re.escape(x).replace(r'\ ', r'[\s\-]') for x in sorted(set(names), key=len, reverse=True))
    return re.compile(r'(?<![\w])(?:' + alts + r')(?:s|es)?(?![\w])', re.I)

def build_entries(pages, data):
    E = {}
    def entry(head, kind, **kw):
        key = (slug(head), kind)
        e = E.setdefault(key, {'head': head, 'kind': kind, 'href': None, 'gloss': '', 'tags': [], 'uses': {}, 'aliases': set(), 'see': None, 'ext': '', 'drawing': None})
        for k, v in kw.items():
            if v and not e.get(k): e[k] = v
        return e
    kind_over = data.get('kinds', {})
    by_url = {p['url']: p for p in pages}
    # pages, guide entries
    for p in pages:
        if p['sec'] == 'guide' and not p['hub']:
            kind = kind_over.get(p['url'], 'term')
            e = entry(p['title'], kind, href=p['url'], gloss=p['tagline'] or p['desc'])
            e['tags'] = ['Field guide']; p['entry'] = e
            for n in p['tree'].walk():                      # "Related term" in the infobox: cross-references
                if n.tag == 'div' and n.kids and isinstance(n.kids[0], N) and n.kids[0].tag == 'dt' and n.kids[0].text().lower() == 'related term':
                    dd = next((k for k in n.kids if isinstance(k, N) and k.tag == 'dd'), None)
                    if dd:
                        for t in re.split(r',| and ', re.sub(r'\[\d+\]', '', dd.text())):
                            t = t.strip(' .')
                            if t: data.setdefault('see', []).append({'from': t[:1].upper() + t[1:], 'to': p['title']})
        else:
            tag = SECTION_LABEL.get(p['sec'], 'Page') if not p['hub'] else 'Section'
            if p['url'].rstrip('/') in ('patterns', 'icons'): tag = 'Lab'
            e = entry(p['title'], 'page', href=p['url'], gloss=p['desc']); e['tags'] = [tag]; p['entry'] = e
    # curated and marked terms and places
    for t in data.get('terms', []): entry(t['term'], 'term').update(aliases=set(t.get('aliases', [])), gloss=t.get('note', ''))
    for t in data.get('places', []):
        e = entry(t['name'], 'place'); e['aliases'] |= set(t.get('aliases', [])); e['gloss'] = e['gloss'] or t.get('note', '')
    for p in pages:
        for n in p['tree'].walk():
            for attr, kind in (('data-term', 'term'), ('data-place', 'place')):
                if attr in n.a and n.a[attr]:
                    nm = clean(n.a[attr].replace('-', ' ')); nm = nm[:1].upper() + nm[1:]
                    if kind == 'term' and ('class' in n.a and 'rv-term' in n.cls()) and n.text(): nm = n.text()
                    entry(nm, kind)
            if 'rv-term' in n.cls() and n.text() and 'data-term' not in n.a:
                entry(n.text(), 'term')
            if n.tag == 'dfn' and n.text(): entry(n.text(), 'term')
    # aliases: curated + guide titles
    alias_of = {}
    for s in data.get('see', []):
        to = next((e for (k, kd), e in E.items() if k == slug(s['to']) and kd in ('term', 'place')), None)
        if not to: print('atlas: see-reference target not found:', s['to'], file=sys.stderr); continue
        if slug(s['from']) in {k for (k, _) in E}: continue
        e = entry(s['from'], 'term'); e['see'] = to; to['aliases'].add(s['from'])
    # mentions
    matchers = []
    for (k, kind), e in list(E.items()):
        if kind in ('term', 'place') and not e['see']:
            matchers.append((e, pattern([e['head']] + sorted(e['aliases']))))
    for p in pages:
        if p['hub']: continue                                # section hubs only list things; they are not uses
        for n, aid, label in anchored(p):
            if n.tag not in ('p', 'li', 'dd', 'td', 'figcaption', 'blockquote', 'h2', 'h3', 'summary') or in_skipped(n): continue
            if any(a is not n and a.tag in ('li', 'p', 'dd', 'td', 'figcaption') for a in n.up()) and n.tag in ('p',): pass
            txt = n.text()
            if len(txt) < 3: continue
            for e, rx in matchers:
                if e.get('href') == p['url'] or (e.get('page') is p): continue
                if rx.search(txt):
                    d = e['uses'].setdefault(p['url'], {'title': p['title'], 'anchors': []})
                    if (aid, label) not in [(a, l) for a, l in d['anchors']] and not (aid is None and d['anchors']): d['anchors'].append((aid, label))
            # explicit links to a guide entry count as uses of it even if the visible text differs
            for a in n.walk():
                if a.tag == 'a' and a.a.get('href') and not a.a['href'].startswith(('http', '#', 'mailto')):
                    tgt = (page_url_of(p['file'], a.a['href']))
                    q = by_url.get(tgt)
                    if q and q.get('entry') and q['entry']['kind'] in ('term', 'place') and q['url'] != p['url'] and q['sec'] == 'guide':
                        d = q['entry']['uses'].setdefault(p['url'], {'title': p['title'], 'anchors': []})
                        if (aid, label) not in d['anchors'] and not (aid is None and d['anchors']): d['anchors'].append((aid, label))
    # a place or term that nothing mentions and nothing defines is not an entry
    for key in [k for k, e in E.items() if e['kind'] in ('term', 'place') and not e['href'] and not e['see'] and not e['uses']]: del E[key]
    # sources, merged by URL
    S = {}
    for p in pages:
        for s in extract_sources(p):
            e = S.setdefault(s['key'], {'head': s['text'], 'url': s['url'], 'kind': s['kind'], 'uses': {}})
            u = e['uses'].setdefault(p['url'], {'title': p['title'], 'anchors': [], 'cites': []})
            for uid, aid, label in s['uses']: u['cites'].append((uid or aid, label))
            if len(s['text']) > len(e['head']): e['head'] = s['text']
    for key, s in S.items():
        e = {'head': s['head'], 'kind': 'source', 'href': None, 'gloss': '', 'tags': [s['kind']] if s['kind'] else [], 'uses': s['uses'], 'aliases': set(), 'see': None, 'ext': s['url'], 'drawing': None}
        E[('src-' + key, 'source')] = e
    # drawings: one source of truth is assets/drawings.json (scripts/build_drawings.py, step one of regen.py);
    # until that file exists, fall back to the captions found here
    dj = root / 'assets' / 'drawings.json'
    titles = {p['url']: p['title'] for p in pages}
    if dj.exists():
        for d in json.loads(dj.read_text(encoding='utf-8')).get('drawings', []):
            pt = titles.get(d['page'], d['page'].strip('/').split('/')[-1].replace('-', ' ').title())
            tag = (f"Fig. {d['fig']} · " if d.get('fig') else '') + pt
            gloss = ' '.join(x.rstrip('.') + '.' for x in (d.get('caption', ''), d.get('note', '')) if x)
            e = {'head': d['label'], 'kind': 'drawing', 'href': 'drawings/#' + d['id'], 'gloss': short(gloss, 220), 'tags': [tag], 'uses': {}, 'aliases': set(), 'see': None, 'ext': '', 'drawing': d}
            if d['page'] in titles:
                e['uses'][d['page']] = {'title': pt, 'anchors': [(d['anchor'], d.get('heading') or '')] if d.get('anchor') else []}
            E[('fig-' + d['id'], 'drawing')] = e
        return E
    for p in pages:
        for f in extract_figures(p):
            tag = (f['num'] + ' · ' if f['num'] else '') + p['title']
            e = {'head': f['head'], 'kind': 'drawing', 'href': p['url'] + ('#' + f['anchor'] if f['anchor'] else ''), 'gloss': f['cap'], 'tags': [tag], 'uses': {}, 'aliases': set(), 'see': None, 'ext': '', 'drawing': f}
            E[('fig-' + p['url'] + str(len(E)), 'drawing')] = e
    return E

def page_url_of(f, href):
    path = href.split('#')[0].split('?')[0]
    if not path: return None
    t = (root / path.lstrip('/')) if path.startswith('/') else (f.parent / path)
    try: t = t.resolve().relative_to(root)
    except Exception: return None
    s = t.as_posix()
    return s[:-len('index.html')] if s.endswith('index.html') else (s + '/' if (root / t).is_dir() else s)

def rel(url, anchor=None): return '../' + url + (('#' + anchor) if anchor else '')

def sortkey(e):
    h = e['head']
    if e['kind'] in ('page', 'drawing'): h = re.sub(r'^(the|a|an)\s+', '', h, flags=re.I)
    h = re.sub(r'^[^A-Za-z0-9]+', '', h)
    return h.casefold()

def render(E):
    rows = []
    ids = set()
    for (_, kind), e in E.items():
        h = e['head']
        if not h: continue
        sk = sortkey(e)
        letter = sk[:1].upper() if sk[:1].isalpha() else '0'
        base = 'e-' + slug(h)[:60]; eid = base; i = 2
        while eid in ids: eid = f'{base}-{i}'; i += 1
        ids.add(eid); e['id'] = eid; rows.append((letter, sk, KIND_ORDER[kind], e))
    rows.sort(key=lambda r: (r[0] == '0' and '\0' or r[0], r[1], r[2]))
    letters = ['0'] + [chr(c) for c in range(65, 91)]
    have = {r[0] for r in rows}
    counts = {k: sum(1 for r in rows if r[3]['kind'] == k and not r[3]['see']) for k in KIND_ORDER}
    total = sum(counts.values())
    L = []
    L.append('<div class="rv-az__facts"><dl>' + ''.join(
        f'<div><dt>{lab}</dt><dd>{counts[k]}</dd></div>' for k, lab in (('term', 'Terms'), ('place', 'Places'), ('source', 'Sources'), ('drawing', 'Drawings'), ('page', 'Pages'))) + '</dl></div>')
    chips = '<button class="rds-chip" type="button" data-az-kind="all" aria-pressed="true">All <i>' + str(total) + '</i></button>' + ''.join(
        f'<button class="rds-chip" type="button" data-az-kind="{k}" aria-pressed="false">{lab} <i>{counts[k]}</i></button>'
        for k, lab in (('term', 'Terms'), ('place', 'Places'), ('source', 'Sources'), ('drawing', 'Drawings'), ('page', 'Pages')))
    L.append('<div class="rv-az__tools"><div class="rds-guide-search"><svg class="rds-icon" aria-hidden="true"><use href="../assets/rds/icons/icons.svg#i-search"/></svg>'
             '<input type="search" data-az-q placeholder="Filter the index: a word, a place, an author" aria-label="Filter the A to Z index" autocomplete="off" spellcheck="false"></div>'
             '<div class="rds-chips" role="group" aria-label="Filter by kind">' + chips + '</div>'
             f'<p class="rds-guide-count" data-az-count aria-live="polite">{total} entries</p></div>')
    L.append('<nav class="rv-az__jump" aria-label="Jump to a letter" data-az-jump><div class="rv-az__jump-in">' + ''.join(
        (f'<a href="#az-{l.lower()}" data-az-letter="{l}">{"0–9" if l == "0" else l}</a>' if l in have else f'<span aria-disabled="true" data-az-letter="{l}">{"0–9" if l == "0" else l}</span>') for l in letters) + '</div></nav>')
    L.append('<div class="rv-az__list" data-az-list data-rv-noindex>')
    cur = None
    for letter, sk, _, e in rows:
        if letter != cur:
            if cur is not None: L.append('</ul></section>')
            cur = letter
            L.append(f'<section class="rv-az__group" id="az-{letter.lower()}" data-az-group="{letter}"><h2 class="rv-az__letter"><span>{"0–9" if letter == "0" else letter}</span><small data-az-n></small></h2><ul class="rv-az__entries">')
        L.append(render_entry(e))
    if cur is not None: L.append('</ul></section>')
    L.append('<p class="rv-az__empty" data-az-empty hidden><b>Nothing matches.</b> <span>Try a shorter word, or a different kind.</span> <button type="button" class="rds-btn rds-btn--ghost rds-btn--sm" data-az-clear>Clear the filter</button></p></div>')
    return '\n'.join(L), counts

def render_entry(e):
    kind = e['kind']; h = esc(e['head'])
    label = {'term': 'Term', 'place': 'Place', 'page': 'Page', 'drawing': 'Drawing', 'source': 'Source'}[kind]
    keys = ' '.join([e['head']] + sorted(e['aliases']) + [e['gloss']] + e['tags'] + [u['title'] for u in e['uses'].values()])
    attr = f'class="rv-az__entry rv-az__entry--{kind}" id="{e["id"]}" data-az-kind-of="{kind}" data-az-text="{esc(keys.lower())}"'
    if e['see']:
        return (f'<li {attr}><p class="rv-az__line"><span class="rv-az__head">{h}</span><span class="rds-tag">{label}</span></p>'
                f'<p class="rv-az__see">See <a href="#{e["see"]["id"]}" data-az-goto>{esc(e["see"]["head"])}</a></p></li>')
    tags = f'<span class="rds-tag rds-tag--brick">{label}</span>' + ''.join(f'<span class="rv-az__tag">{esc(t)}</span>' for t in e['tags'])
    if kind == 'source':
        head = f'<span class="rv-az__head rv-az__head--cite">{h}</span>'
        ext = f'<a class="rv-az__ext" href="{esc(e["ext"])}" rel="noopener">Open the source <span aria-hidden="true">↗</span></a>' if e['ext'] else ''
    elif e['href']:
        head = f'<a class="rv-az__head" href="{esc(rel(e["href"]))}">{h}</a>'; ext = ''
    else:
        head = f'<span class="rv-az__head">{h}</span>'; ext = ''
    out = [f'<li {attr}><p class="rv-az__line">{head}{tags}</p>']
    if e['gloss'] and kind != 'source' and not (kind == 'drawing' and e['gloss'].lower().startswith(e['head'].lower().rstrip('…'))): out.append(f'<p class="rv-az__gloss">{esc(e["gloss"])}</p>')
    if e['uses']:
        items = []
        for url, u in sorted(e['uses'].items(), key=lambda kv: kv[0]):
            if kind == 'source':
                links = ''.join(f'<a href="{esc(rel(url, a))}" aria-label="Use {i} in {esc(u["title"])}{(", " + esc(lb)) if lb else ""}">{i}</a>' for i, (a, lb) in enumerate(u['cites'][:12], 1)) if u['cites'] else ''
                more = f' <span class="rv-az__at">{len(u["cites"])} use{"s" if len(u["cites"]) != 1 else ""} {links}</span>' if u['cites'] else ''
            else:
                links = ', '.join(f'<a href="{esc(rel(url, a))}">{esc(short(lb, 38)) if lb else "Intro"}</a>' for a, lb in u['anchors'][:MAX_ANCHORS] if a or True)
                more = f' <span class="rv-az__at">{links}</span>' if links else ''
            items.append(f'<li><a class="rv-az__page" href="{esc(rel(url))}">{esc(u["title"])}</a>{more}</li>')
        n = len(items); lab = {'source': 'Cited on', 'drawing': 'Appears on'}.get(kind, 'Used on')
        head_html = f'<p class="rv-az__uses-h">{lab} <b>{n}</b> page{"s" if n != 1 else ""}</p>'
        if n > MAX_PAGES:
            out.append(f'<div class="rv-az__uses">{head_html}<ul>{"".join(items[:MAX_PAGES])}</ul><details><summary>{n - MAX_PAGES} more</summary><ul>{"".join(items[MAX_PAGES:])}</ul></details></div>')
        else:
            out.append(f'<div class="rv-az__uses">{head_html}<ul>{"".join(items)}</ul></div>')
    elif kind == 'drawing':
        pass
    if ext: out.append(f'<p class="rv-az__foot">{ext}</p>')
    out.append('</li>')
    return ''.join(out)

def build():
    data = json.loads(DATA.read_text(encoding='utf-8')) if DATA.exists() else {}
    pages = load_pages()
    E = build_entries(pages, data)
    body, counts = render(E)
    # resolve see-references that were created before ids existed
    for e in E.values():
        pass
    src = PAGE.read_text(encoding='utf-8')
    if START not in src or END not in src: sys.exit(f'a-z/index.html is missing the {START} / {END} markers')
    out = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda m: START + '\n' + body + '\n' + END, src, flags=re.S)
    return {'a-z/index.html': out}, counts

