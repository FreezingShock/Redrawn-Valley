#!/usr/bin/env python3
"""Generate the A-Z Index (a-z/index.html) from the site's own pages.
Run: python3 scripts/build_atlas.py          rewrite the generated region of a-z/index.html
     python3 scripts/build_atlas.py --check  exit 1 if it is stale (also run by build_index.py --check and scripts/check.py)
build_index.py calls this too, so `python3 scripts/build_index.py` refreshes everything generated.

Entry kinds and where they come from (nothing here is hand-listed except scripts/data/atlas.json, which only adds
aliases, cross-references and place names):
  page     every other indexed page: studies, notes, lab notes, section hubs
  term     each field guide entry (its title), plus anything marked data-term / class rv-term / <dfn>,
           plus the terms in atlas.json; text mentions are found automatically
  place    names in atlas.json and anything marked data-place; mentions found automatically
  source   every <li> in a sources list (ol.rds-notes, .rv-sources, #sources), merged across pages by URL;
           uses are the in-text links that point at that list item
  drawing  every <figure> with a caption and every infobox sketch caption
A new article needs nothing: its title, figures, sources and any mention of an existing term or place are picked up the
next time this runs. To add a term or place, add it to scripts/data/atlas.json or mark it up with data-term / data-place."""
